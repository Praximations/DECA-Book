// DECA Book Studio: a small local editor.  `npm run studio`  ->  http://localhost:4321
//
// • Live preview of the book: every save in VS Code rebuilds and refreshes the page.
// • Click any element in the preview to edit its text, swap its photo, or open its
//   source line in VS Code. Edits are written straight back into src/pages/*.html.
// • Brand kit: change the colours, fonts and sizes in tokens.css with live preview.
// • Book details: the title-page facts in book.config.json.
// • Export: PDF, PowerPoint + Canva kit, condensed PDF, the penalty check.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as parse5 from 'parse5';
import { build, fillPage, pageFiles, SRC } from './build.mjs';
import { ROOT, DIST, config, mb } from './lib.mjs';

const PORT = +process.env.PORT || 4321;
const STUDIO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'studio');
const PAGES = path.join(SRC, 'pages');
const TOKENS = path.join(SRC, 'styles/tokens.css');
const CONFIG = path.join(ROOT, 'book.config.json');
const RAW_IMAGES = path.join(SRC, 'assets/images/raw');
const TASKS = { pdf: 'PDF', canva: 'PowerPoint + Canva kit', condense: 'Condensed PDF', check: 'Penalty check', all: 'Everything' };

/* ---------- live reload ---------- */
const clients = new Set();
const send = (event, data) => { for (const res of clients) res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`); };
let timer = null, building = false, again = false;
async function rebuild() {
  if (building) { again = true; return; }
  building = true;
  try { await build({ quiet: true }); send('reload', { at: Date.now() }); }
  catch (e) { send('log', { text: '✗ build failed: ' + e.message }); }
  building = false;
  if (again) { again = false; rebuild(); }
}
const schedule = () => { clearTimeout(timer); timer = setTimeout(rebuild, 150); };
fs.watch(SRC, { recursive: true }, (ev, name) => { if (name && !/assets[\\/]images[\\/]optimized/.test(name)) schedule(); });
fs.watch(CONFIG, schedule);

/* ---------- source mapping ---------- */
/** Position in the built page -> position in the source file (null if inside a {{placeholder}}). */
function toSrc(map, off) {
  let delta = 0;
  for (const r of map) {
    if (off <= r.outStart) return off + delta;
    if (off < r.outEnd) return null;
    delta = r.srcEnd - r.outEnd;
  }
  return off + delta;
}
const lineOf = (text, off) => text.slice(0, off).split('\n').length;

/** Finds the element at `idxPath` (child-element indices from the page section) in a page file. */
function locate(file, idxPath) {
  if (!pageFiles().includes(file)) throw new Error(`unknown page ${file}`);
  const src = fs.readFileSync(path.join(PAGES, file), 'utf8');
  const { html, map } = fillPage(src, config());
  const frag = parse5.parseFragment(html, { sourceCodeLocationInfo: true });
  let node = frag.childNodes.find((n) => n.tagName);
  for (const i of idxPath) {
    node = node.childNodes.filter((n) => n.tagName)[i];
    if (!node) throw new Error('element not found in the source (was it generated by runtime.js?)');
  }
  const loc = node.sourceCodeLocation;
  const start = toSrc(map, loc.startOffset);
  return { src, map, node, loc, start, line: start === null ? null : lineOf(src, start) };
}
function tokenInside(map, a, b) { return map.find((r) => r.outStart >= a && r.outEnd <= b && !(r.outStart === a && r.outEnd === a)); }

function editInner(file, idxPath, innerHTML) {
  const { src, map, loc } = locate(file, idxPath);
  if (!loc.endTag) throw new Error('this element has no inner text');
  const a = loc.startTag.endOffset, b = loc.endTag.startOffset;
  const tok = tokenInside(map, a, b);
  if (tok) throw new Error(`this text is filled from book.config.json (${tok.token}); change it under Book details`);
  const sa = toSrc(map, a), sb = toSrc(map, b);
  if (sa === null || sb === null) throw new Error('this element starts inside a placeholder');
  fs.writeFileSync(path.join(PAGES, file), src.slice(0, sa) + innerHTML + src.slice(sb));
}
function editAttr(file, idxPath, name, value) {
  if (!/^[a-z-]+$/.test(name)) throw new Error('bad attribute name');
  const { src, map, loc } = locate(file, idxPath);
  const tag = loc.startTag;
  const attr = loc.attrs && loc.attrs[name];
  const esc = String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;');
  let sa, sb, text;
  if (attr) {
    sa = toSrc(map, attr.startOffset); sb = toSrc(map, attr.endOffset);
    text = value === null ? '' : `${name}="${esc}"`;
  } else {
    if (value === null) return;
    const close = tag.endOffset - (src.slice(toSrc(map, tag.endOffset) - 2, toSrc(map, tag.endOffset)) === '/>' ? 2 : 1);
    sa = sb = toSrc(map, close);
    text = ` ${name}="${esc}"`;
  }
  if (sa === null || sb === null) throw new Error('this attribute sits inside a placeholder');
  fs.writeFileSync(path.join(PAGES, file), (src.slice(0, sa) + text + src.slice(sb)).replace(/\s+(\/?>)/g, (m, g) => (m.includes('\n') ? m : g)));
}

/* ---------- tokens, config, images, outputs ---------- */
function readTokens() {
  const css = fs.readFileSync(TOKENS, 'utf8');
  const out = [];
  for (const m of css.matchAll(/^\s*(--[\w-]+)\s*:\s*([^;]+);[ \t]*(?:\/\*\s*(.*?)\s*\*\/)?/gm)) {
    out.push({ name: m[1], value: m[2].trim(), note: (m[3] || '').trim() });
  }
  return out;
}
function writeToken(name, value) {
  if (!/^--[\w-]+$/.test(name) || /[;{}]/.test(value)) throw new Error('bad token');
  const css = fs.readFileSync(TOKENS, 'utf8');
  const re = new RegExp(`(^\\s*${name.replace(/[-]/g, '\\-')}\\s*:\\s*)([^;]+)(;)`, 'm');
  if (!re.test(css)) throw new Error(`token ${name} not found`);
  fs.writeFileSync(TOKENS, css.replace(re, `$1${value}$3`));
}
function writeConfig(key, value) {
  const cfg = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  if (!(key in cfg) || typeof cfg[key] === 'object' && !Array.isArray(cfg[key])) throw new Error(`cannot edit ${key} here`);
  cfg[key] = Array.isArray(cfg[key]) ? String(value).split('\n').map((s) => s.trim()).filter(Boolean) : value;
  fs.writeFileSync(CONFIG, JSON.stringify(cfg, null, 2) + '\n');
}
const OPT = path.join(SRC, 'assets/images/optimized');
const images = () => fs.readdirSync(RAW_IMAGES).filter((f) => !f.startsWith('.')).sort().map((f) => {
  const base = f.replace(/\.[^.]+$/, '');
  const built = /\.svg$/i.test(f) ? f : fs.existsSync(path.join(OPT, base + '.png')) ? base + '.png' : base + '.jpg';
  return { raw: f, built: 'assets/images/' + built };
});
function outputs() {
  const cfg = config(), name = cfg.outputName || 'DECA-Book';
  return [`${name}.pdf`, `${name}-compact.pdf`, `${name}.pptx`, `${name}-Canva-Kit.zip`]
    .filter((f) => fs.existsSync(path.join(DIST, f)))
    .map((f) => ({ file: f, size: mb(fs.statSync(path.join(DIST, f)).size), when: fs.statSync(path.join(DIST, f)).mtime }));
}
function state() {
  const cfg = config();
  const editable = Object.fromEntries(Object.entries(cfg).filter(([k, v]) => typeof v === 'string' || (Array.isArray(v) && v.every((x) => typeof x === 'string'))));
  return { root: ROOT, pages: pageFiles(), config: editable, tokens: readTokens(), images: images(), outputs: outputs(), tasks: TASKS, limit: cfg.limits.pdfMegabytes };
}

/* ---------- tasks ---------- */
let running = null;
function run(task) {
  if (!TASKS[task]) throw new Error('unknown task');
  if (running) throw new Error(`${TASKS[running]} is still running`);
  running = task;
  send('log', { text: `▶ ${TASKS[task]}…`, start: true });
  const child = spawn('npm', ['run', task, '--silent'], { cwd: ROOT, env: process.env });
  const relay = (chunk) => chunk.toString().split('\n').filter((l) => l.trim()).forEach((text) => send('log', { text }));
  child.stdout.on('data', relay); child.stderr.on('data', relay);
  child.on('close', (code) => { running = null; send('done', { task, code, outputs: outputs() }); });
}

/* ---------- http ---------- */
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.woff2': 'font/woff2', '.woff': 'font/woff', '.pdf': 'application/pdf', '.pptx': 'application/vnd.openxmlformats-officedocument.presentationml.presentation', '.zip': 'application/zip' };
const json = (res, code, data) => { res.writeHead(code, { 'Content-Type': 'application/json' }); res.end(JSON.stringify(data)); };
const body = (req) => new Promise((ok, no) => { let s = ''; req.on('data', (c) => (s += c)); req.on('end', () => { try { ok(s ? JSON.parse(s) : {}); } catch (e) { no(e); } }); });
function serve(res, file) {
  if (!fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); return res.end('not found'); }
  res.writeHead(200, { 'Content-Type': TYPES[path.extname(file).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store' });
  fs.createReadStream(file).pipe(res);
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, 'http://x');
  try {
    if (url.pathname === '/') return serve(res, path.join(STUDIO, 'index.html'));
    if (url.pathname === '/events') {
      res.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', Connection: 'keep-alive' });
      res.write('event: hello\ndata: {}\n\n');
      clients.add(res);
      const ping = setInterval(() => res.write(': ping\n\n'), 25000);
      req.on('close', () => { clearInterval(ping); clients.delete(res); });
      return;
    }
    if (url.pathname === '/api/state') return json(res, 200, state());
    if (req.method === 'POST' && url.pathname.startsWith('/api/')) {
      const b = await body(req);
      switch (url.pathname) {
        case '/api/edit': editInner(b.file, b.path, b.innerHTML); return json(res, 200, { ok: true });
        case '/api/attr': editAttr(b.file, b.path, b.name, b.value); return json(res, 200, { ok: true });
        case '/api/token': writeToken(b.name, b.value); return json(res, 200, { ok: true });
        case '/api/config': writeConfig(b.key, b.value); return json(res, 200, { ok: true });
        case '/api/locate': { const l = locate(b.file, b.path); return json(res, 200, { line: l.line, file: path.join(PAGES, b.file) }); }
        case '/api/run': run(b.task); return json(res, 200, { ok: true });
        default: return json(res, 404, { error: 'unknown api' });
      }
    }
    if (url.pathname.startsWith('/studio/')) return serve(res, path.join(STUDIO, path.normalize(url.pathname.slice(8))));
    if (url.pathname.startsWith('/raw-images/')) return serve(res, path.join(RAW_IMAGES, path.basename(decodeURIComponent(url.pathname))));
    return serve(res, path.join(DIST, path.normalize(decodeURIComponent(url.pathname))));
  } catch (e) {
    return json(res, 400, { error: e.message });
  }
});

await build({ quiet: true });
server.listen(PORT, '127.0.0.1', () => {
  console.log(`\n  DECA Book Studio  →  http://localhost:${PORT}\n  Watching src/ and book.config.json. Press Ctrl+C to stop.\n`);
});
